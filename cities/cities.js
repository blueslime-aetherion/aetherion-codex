const detailBox = document.getElementById("detail");

const cityContent = document.getElementById("city-content");






function openRegion(id){



let region = regions[id];



let html = `



<h1>
${region.title}
</h1>


<h2>
${region.subtitle}
</h2>



`;






/* KINGDOM */


region.kingdoms.forEach(kingdom=>{


html += `


<h2>
🏰 ${kingdom.name}
</h2>


`;




kingdom.cities.forEach(city=>{



html += `



<div class="city-item">


<h3>

${city.name}

</h3>



<div class="city-type">

${city.type}

</div>



<p>

${city.desc}

</p>



<h4>
Information
</h4>



<ul>

`;




city.info.forEach(data=>{


html += `

<li>
${data}
</li>

`;


});



html += `

</ul>


</div>


`;



});



});








/* LANDMARK */


if(region.landmarks.length > 0){



html += `


<h2>
🗺 Important Landmarks
</h2>


<ul>

`;



region.landmarks.forEach(place=>{


html += `


<li>
${place}
</li>


`;


});



html += `

</ul>


`;



}






cityContent.innerHTML = html;



detailBox.style.display="flex";



}









function closeDetail(){



detailBox.style.display="none";


}






